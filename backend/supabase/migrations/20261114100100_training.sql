-- ============================================================================
-- Training log: exercises, workouts, workout_exercises, sets
-- ============================================================================
-- What this migration does, in plain language:
--   This is the core of Astra — the tables a logged workout lives in. A
--   workout is a tree: one `workouts` row, with `workout_exercises` entries
--   (bench press, then squats, ...) each holding `sets` rows (the actual reps
--   and weight). `exercises` is the movement catalogue those entries point at.
--
--   Offline-first design decision: the phone creates workout rows while the
--   user may have no signal, so ALL ids in the workout tree are generated by
--   the client (UUIDs), never by the server. Syncing is then an idempotent
--   upsert — if the app retries after a dropped connection, the same id lands
--   on the same row and nothing is duplicated (FND-3's schema half).
--
--   Privacy: a workout is 'public', 'followers', or 'private'. Row-level
--   security enforces this at the database — the child tables (entries, sets)
--   inherit the parent workout's visibility through helper functions, so the
--   rule lives in exactly one place.
-- ============================================================================

-- ============================================================================
-- exercises — the movement catalogue
-- ============================================================================
-- Two kinds of rows share this table:
--   owner_id IS NULL  → a shared library exercise everyone can see (seeded
--                       later by the Library build items).
--   owner_id = a user → that user's private custom exercise.
create table public.exercises (
  id             uuid primary key default gen_random_uuid(),
  owner_id       uuid references public.profiles (id) on delete cascade,
  name           text not null check (char_length(name) between 1 and 80),
  -- Free-text for now; a structured muscle/equipment taxonomy arrives with the
  -- Library build items, which own that vocabulary.
  primary_muscle text,
  equipment      text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create index exercises_owner_idx on public.exercises (owner_id);

alter table public.exercises enable row level security;

create trigger set_updated_at
  before update on public.exercises
  for each row execute function extensions.moddatetime (updated_at);

-- Everyone signed in can read the shared library plus their own customs.
create policy "library and own exercises are readable"
  on public.exercises for select
  to authenticated
  using (owner_id is null or owner_id = (select auth.uid()));

-- Users manage only their own custom exercises. Library rows (owner_id null)
-- can never be created or touched through the client API.
create policy "users create their own exercises"
  on public.exercises for insert
  to authenticated
  with check (owner_id = (select auth.uid()));

create policy "users update their own exercises"
  on public.exercises for update
  to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

create policy "users delete their own exercises"
  on public.exercises for delete
  to authenticated
  using (owner_id = (select auth.uid()));

-- ============================================================================
-- workouts — one logged session
-- ============================================================================
create table public.workouts (
  -- Client-generated (the phone makes the UUID while offline) — no default on
  -- purpose: the server must never invent an id the phone doesn't know about.
  id         uuid primary key,
  user_id    uuid not null references public.profiles (id) on delete cascade,
  title      text check (char_length(title) <= 100),
  notes      text check (char_length(notes) <= 2000),
  started_at timestamptz not null,
  -- Null while the workout is still in progress on the phone.
  ended_at   timestamptz check (ended_at is null or ended_at >= started_at),
  visibility public.workout_visibility not null default 'public',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- The profile screen and feed both read "this user's workouts, newest first".
create index workouts_user_started_idx on public.workouts (user_id, started_at desc);

alter table public.workouts enable row level security;

create trigger set_updated_at
  before update on public.workouts
  for each row execute function extensions.moddatetime (updated_at);

-- ----------------------------------------------------------------------------
-- Visibility helpers — THE single home of the "who can see a workout" rule
-- ----------------------------------------------------------------------------
-- All three live in the `private` schema so the API cannot call them directly,
-- and are SECURITY DEFINER so they can consult follows/blocks/workouts without
-- being re-filtered by those tables' own RLS (which would hide the very rows
-- the rule needs to check).

-- Can the current user see a workout owned by `owner` with visibility `vis`?
--   * You always see your own.
--   * A block in either direction hides everything.
--   * Otherwise: 'public' is open to any signed-in user, 'followers' requires
--     that the viewer follows the owner, 'private' is owner-only.
create or replace function private.workout_visible(owner uuid, vis public.workout_visibility)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    owner = (select auth.uid())
    or (
      not exists (
        select 1 from public.blocks b
        where (b.blocker_id = owner and b.blocked_id = (select auth.uid()))
           or (b.blocker_id = (select auth.uid()) and b.blocked_id = owner)
      )
      and (
        vis = 'public'
        or (
          vis = 'followers'
          and exists (
            select 1 from public.follows f
            where f.follower_id = (select auth.uid()) and f.followee_id = owner
          )
        )
      )
    )
$$;

-- Same question, answered from a workout id — used by the child tables.
create or replace function private.can_view_workout(wid uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.workouts w
    where w.id = wid and private.workout_visible(w.user_id, w.visibility)
  )
$$;

-- Does the current user OWN this workout? Gate for all child-table writes.
create or replace function private.owns_workout(wid uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.workouts w
    where w.id = wid and w.user_id = (select auth.uid())
  )
$$;

-- ----------------------------------------------------------------------------
-- workouts policies
-- ----------------------------------------------------------------------------
create policy "workouts readable per their visibility"
  on public.workouts for select
  to authenticated
  using (private.workout_visible(user_id, visibility));

create policy "users log workouts as themselves"
  on public.workouts for insert
  to authenticated
  with check (user_id = (select auth.uid()));

create policy "users update their own workouts"
  on public.workouts for update
  to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

create policy "users delete their own workouts"
  on public.workouts for delete
  to authenticated
  using (user_id = (select auth.uid()));

-- ============================================================================
-- workout_exercises — one exercise's slot inside a workout
-- ============================================================================
-- "Bench press, third exercise of Tuesday's session." Sets hang off this row.
create table public.workout_exercises (
  id            uuid primary key,  -- client-generated, like workouts.id
  workout_id    uuid not null references public.workouts (id) on delete cascade,
  exercise_id   uuid not null references public.exercises (id),
  -- Display order within the workout (0, 1, 2, ...). Not unique-constrained:
  -- offline reorder syncs row-by-row and would trip a uniqueness check midway.
  position      smallint not null check (position >= 0),
  notes         text check (char_length(notes) <= 1000),
  -- Entries sharing the same number form a superset (e.g. both marked 1).
  -- Null = not part of a superset.
  superset_group smallint,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index workout_exercises_workout_idx on public.workout_exercises (workout_id);
create index workout_exercises_exercise_idx on public.workout_exercises (exercise_id);

alter table public.workout_exercises enable row level security;

create trigger set_updated_at
  before update on public.workout_exercises
  for each row execute function extensions.moddatetime (updated_at);

-- Readable exactly when the parent workout is readable; writable only by the
-- workout's owner. The rule itself lives in the helper functions above.
create policy "entries readable with their workout"
  on public.workout_exercises for select
  to authenticated
  using (private.can_view_workout(workout_id));

create policy "owners add entries to their workouts"
  on public.workout_exercises for insert
  to authenticated
  with check (private.owns_workout(workout_id));

create policy "owners update entries in their workouts"
  on public.workout_exercises for update
  to authenticated
  using (private.owns_workout(workout_id))
  with check (private.owns_workout(workout_id));

create policy "owners delete entries in their workouts"
  on public.workout_exercises for delete
  to authenticated
  using (private.owns_workout(workout_id));

-- ============================================================================
-- sets — the actual work: reps at a weight
-- ============================================================================
create table public.sets (
  id                  uuid primary key,  -- client-generated
  workout_exercise_id uuid not null references public.workout_exercises (id) on delete cascade,
  -- Order within the exercise entry (set 1, set 2, ...).
  position            smallint not null check (position >= 0),
  reps                integer check (reps >= 0),
  -- Always kilograms (see user_settings.unit for display). Null for bodyweight
  -- or timed work with no load.
  weight_kg           numeric(6, 2) check (weight_kg >= 0),
  -- Rating of perceived exertion, optional, standard 1–10 lifting scale in
  -- half-point steps (the numeric(3,1) type allows 7.5 etc.).
  rpe                 numeric(3, 1) check (rpe between 1 and 10),
  -- Warm-up sets are logged but excluded from PRs and analysis later.
  is_warmup           boolean not null default false,
  -- Segments of a drop set: the top set is null, follow-on drops are 1, 2, ...
  drop_set_position   smallint check (drop_set_position >= 1),
  -- For timed work (planks, WOD-style pieces). Reps-and-weight sets leave it
  -- null.
  duration_seconds    integer check (duration_seconds >= 0),
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

create index sets_entry_idx on public.sets (workout_exercise_id);

alter table public.sets enable row level security;

create trigger set_updated_at
  before update on public.sets
  for each row execute function extensions.moddatetime (updated_at);

-- Sets are two levels below the workout, so first look up which workout this
-- set belongs to, then apply the same single visibility/ownership rule.
-- SECURITY DEFINER so the lookup isn't re-filtered by workout_exercises' RLS.
create or replace function private.entry_workout(entry_id uuid)
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select workout_id from public.workout_exercises where id = entry_id
$$;

create policy "sets readable with their workout"
  on public.sets for select
  to authenticated
  using (private.can_view_workout(private.entry_workout(workout_exercise_id)));

create policy "owners add sets to their workouts"
  on public.sets for insert
  to authenticated
  with check (private.owns_workout(private.entry_workout(workout_exercise_id)));

create policy "owners update sets in their workouts"
  on public.sets for update
  to authenticated
  using (private.owns_workout(private.entry_workout(workout_exercise_id)))
  with check (private.owns_workout(private.entry_workout(workout_exercise_id)));

create policy "owners delete sets in their workouts"
  on public.sets for delete
  to authenticated
  using (private.owns_workout(private.entry_workout(workout_exercise_id)));
